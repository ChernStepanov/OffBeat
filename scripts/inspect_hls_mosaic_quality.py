"""Evaluate same-acquisition HLS QA mosaics across both overlapping Caracas tiles."""
import argparse,datetime as dt,hashlib,json,os
from pathlib import Path
import numpy as np,rasterio,requests
from rasterio.warp import transform_bounds
from rasterio.windows import from_bounds
ROOT=Path(__file__).resolve().parents[1]
INDEX=ROOT/'data/venezuela/optical/index.json';OUT=ROOT/'data/subsets/venezuela-hls/2025-11-21-mosaic-quality.json'

def clear_qa(qa):
    return (~np.ma.getmaskarray(qa)) & ((qa.filled(255) & 30) == 0)


def read_clear(granule,bbox,token):
    links=[l['href'] for l in granule['links'] if l.get('href','').startswith('https://data.lpdaac.earthdatacloud.nasa.gov/') and l['href'].endswith('.Fmask.tif')]
    if len(links)!=1:raise ValueError('Missing or ambiguous Fmask')
    r=requests.get(links[0],headers={'Authorization':'Bearer '+token,'Range':'bytes=0-0'},allow_redirects=False,timeout=30)
    if r.status_code!=303:raise RuntimeError('HLS access failed')
    with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN='EMPTY_DIR',GDAL_HTTP_TIMEOUT='30',CPL_VSIL_CURL_ALLOWED_EXTENSIONS='.tif'):
      with rasterio.open('/vsicurl/'+r.headers['Location']) as src:
        bounds=transform_bounds('EPSG:4326',src.crs,bbox['w'],bbox['s'],bbox['e'],bbox['n'])
        win=from_bounds(*bounds,src.transform).round_offsets().round_lengths()
        # Boundless read keeps the full AOI denominator; outside the tile is unavailable.
        qa=src.read(1,window=win,masked=True,boundless=True)
        clear=clear_qa(qa)
        return clear,{'crs':str(src.crs),'shape':list(clear.shape),'transform':[float(v) for v in src.window_transform(win)[:6]],'asset_url':links[0]}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--retry-failures',action='store_true');args=parser.parse_args()
    token=os.environ.get('EARTHDATA_TOKEN') or (ROOT/'.earthdata_token').read_text().strip()
    index=json.loads(INDEX.read_text());b=index['bbox'];groups={};queries=[]
    for collection in ('HLSS30','HLSL30'):
        r=requests.get('https://cmr.earthdata.nasa.gov/search/granules.json',params={'short_name':collection,'bounding_box':','.join(str(b[k]) for k in ('w','s','e','n')),'temporal':'2025-11-06T00:00:00Z,2025-12-06T23:59:59Z','page_size':200,'sort_key':'start_date'},timeout=60);r.raise_for_status();queries.append(r.url)
        items=r.json()['feed']['entry']
        if int(r.headers.get('CMR-Hits',len(items)))>len(items):raise ValueError('Pagination required')
        for g in items:
            ident=g['producer_granule_id'];parts=ident.split('.')
            if len(parts)<4 or parts[2] not in ('T19PGM','T19PFM'):continue
            key=collection+':'+parts[3];tile=parts[2];
            if tile in groups.setdefault(key,{}):raise ValueError('Duplicate tile acquisition')
            groups[key][tile]=g
    receipt={'source':'NASA LP DAAC HLS v2.0 Fmask','nisar_date':'2025-11-21','retrieved_utc':dt.datetime.now(dt.timezone.utc).isoformat(),'queries':queries,'threshold':0.8,
       'method':'Group same HLS collection and acquisition timestamp, read the full projected AOI window from each tile with boundless no-data. Check CRS, transform and dimensions match; count a pixel clear if either tile has valid QA without cloud, adjacent cloud/shadow, shadow or snow/ice (bits 1–4). Require 80% AOI clear. No scenes from different timestamps are combined.',
       'limitations':'HLS Fmask includes a 150 m cloud/shadow adjacency buffer; this is more conservative than Sentinel-2 SCL. No optical image is generated by this inspection. Incomplete/failed reads remain unknown.', 'candidates':[]}
    OUT.parent.mkdir(parents=True,exist_ok=True)
    completed={}
    if args.retry_failures and OUT.exists():
        old=json.loads(OUT.read_text(encoding='utf-8'))
        completed={c['acquisition']:c for c in old['candidates'] if 'clear_fraction' in c and c['acquisition'] in groups and {g['id'] for g in c['granules']}=={g['producer_granule_id'] for g in groups[c['acquisition']].values()}}
        receipt['candidates']=list(completed.values())
    for key,tiles in sorted(groups.items()):
        if key in completed: continue
        item={'acquisition':key,'granules':[{'id':g['producer_granule_id'],'concept_id':g['id']} for g in tiles.values()]}
        try:
            if set(tiles)!= {'T19PGM','T19PFM'}:raise ValueError('Missing overlapping tile')
            masks=[];metas=[]
            for tile in ('T19PGM','T19PFM'):
                mask,meta=read_clear(tiles[tile],b,token);masks.append(mask);metas.append(meta)
            for field in ('crs','shape','transform'):
                if metas[0][field]!=metas[1][field]:raise ValueError('Grid alignment mismatch')
            union=masks[0]|masks[1];item.update({'total_pixels':int(union.size),'clear_pixels':int(union.sum()),'clear_fraction':round(float(union.mean()),6),'assets':[m['asset_url'] for m in metas],'grid':{k:metas[0][k] for k in ('crs','shape','transform')}})
        except Exception as exc:item['error']=type(exc).__name__
        receipt['candidates'].append(item);OUT.write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8');print(key,item.get('clear_fraction',item.get('error')),flush=True)
    print('inspected',len(receipt['candidates']),'best',max([v['clear_fraction'] for v in receipt['candidates'] if 'clear_fraction' in v],default=None),flush=True)

if __name__=='__main__':
    try:main()
    except Exception as exc:
        import sys
        print('HLS mosaic inspection failed:',type(exc).__name__,file=sys.stderr);sys.exit(1)
